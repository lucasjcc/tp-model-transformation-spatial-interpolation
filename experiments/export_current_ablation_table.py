"""Generate a patch for the current ablation table, or audit it with --check.

Run analyze_current_ablation in MATLAB first. Never uses historical summaries
or rounds individual pairs before computing differences and inference.
"""
import argparse
import csv
from decimal import Decimal
import difflib
import math
from pathlib import Path

from export_monte_carlo_tables import DATASETS, RATIOS, SOURCE, load_csvs, reference_directory

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = reference_directory('reviewer1') / 'ablation_summary.csv'
TARGET = ROOT / 'article/manuscrito/tables/reviewer1_ablation.tex'


def load_summary():
    with SUMMARY.open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream))
    expected = [(dataset, Decimal(ratio) / 100) for dataset, _ in DATASETS for ratio in RATIOS]
    assert [(r['dataset'], Decimal(r['ratio'])) for r in rows] == expected
    source, count = load_csvs(SOURCE)
    assert count == 50
    for row in rows:
        assert int(row['n']) == 50 and int(row['csv_summary_matches']) == 1
        for key, value in row.items():
            if key != 'dataset':
                assert math.isfinite(float(value)), (key, value)
        for mean, sd, method in [('mean_tp', 'sd_tp', 'TS (Interp)'),
                                 ('mean_scattered', 'sd_scattered', 'Scattered')]:
            metric = source[row['dataset'], int(Decimal(row['ratio']) * 100)][method]['RMSE']
            assert abs(Decimal(row[mean]) - metric.value) <= Decimal('0.0005001')
            assert abs(Decimal(row[sd]) - Decimal(metric.sd)) <= Decimal('0.0005001')
        assert math.isclose(float(row['mean_delta']),
                            float(row['mean_tp']) - float(row['mean_before']), abs_tol=1e-13)
        se = float(row['sd_delta']) * math.sqrt(1 / 50 + float(row['test_train_ratio']))
        assert math.isclose(se, float(row['corrected_se']), rel_tol=1e-12, abs_tol=1e-15)
        assert float(row['ci_low']) <= float(row['mean_delta']) <= float(row['ci_high'])
        assert float(row['max_csv_rounding_difference']) <= 0.0005001
    largest = 0.0
    for rank, row in enumerate(sorted(rows, key=lambda r: float(r['p']))):
        largest = min(1.0, max(largest, (30 - rank) * float(row['p'])))
        assert math.isclose(largest, float(row['p_holm']), rel_tol=1e-12, abs_tol=1e-14)
        assert bool(int(row['reject_005'])) == (largest < .05)
    return rows


def render(rows):
    lookup = {(r['dataset'], Decimal(r['ratio'])): r for r in rows}
    lines = [
        f'% Source: {SUMMARY.relative_to(ROOT).as_posix()}.',
        '% Generated by experiments/export_current_ablation_table.py; current Random replay.',
        r'\begin{table}[pos=!htbp]', r'\centering',
        r'\caption{Ablação com o mesmo tensor imputado: reconstrução antes e depois do truncamento TP.}',
        r'\label{tab:r1-ablation}', r'\small', r'\begingroup',
        r'\setlength{\tabcolsep}{3pt}', r'\renewcommand{\arraystretch}{1.1}',
        r'\begin{tabular*}{\linewidth}{@{}l@{\extracolsep{\fill}}ccccc@{}}', r'\toprule',
        r'\textbf{Conjunto} & $\rho$ & \textbf{Antes: $B$} & \textbf{Após: TP} & $\overline{d}^{\mathrm{abl}}$ & $p_{\mathrm{Holm}}$ \\',
        r'\midrule',
    ]
    for index, (dataset, label) in enumerate(DATASETS):
        if index:
            lines.append(r'\addlinespace[3pt]')
        for ratio in RATIOS:
            row = lookup[dataset, Decimal(ratio) / 100]
            values = [(f"{float(row[mean]):.4f}", f"{float(row[sd]):.4f}")
                      for mean, sd in [('mean_before', 'sd_before'), ('mean_tp', 'sd_tp')]]
            best = min(Decimal(mean) for mean, _ in values)
            cells = []
            for mean, sd in values:
                if Decimal(mean) == best:
                    mean, sd = rf'\mathbf{{{mean}}}', rf'\mathbf{{{sd}}}'
                cells.append(rf'\rmsecell{{{mean}}}{{{sd}}}')
            mantissa, exponent = f"{float(row['mean_delta']):+.2e}".split('e')
            difference = rf'${mantissa}\times10^{{{int(exponent)}}}$'
            lines.append(f'{label if ratio == 10 else ""} & ${ratio}\\%$ & ' +
                         ' & '.join(cells) + f" & {difference} & {float(row['p_holm']):.3f} " + r'\\')
    rejected = sum(int(r['reject_005']) for r in rows)
    inference = ('Nenhum contraste foi significativo a $5\\%$ após Holm.' if rejected == 0 else
                 f'{rejected} dos 30 contrastes foram significativos a $5\\%$ após Holm.')
    lines += [r'\bottomrule', r'\end{tabular*}', r'\par\smallskip',
              r'\begin{minipage}{\linewidth}', r'\footnotesize\raggedright',
              r'\textit{Nota:} RMSE médio $\pm$ desvio padrão amostral em 50 partições por configuração, '
              r'em nova reprodução com coordenadas originais e geometria euclidiana. $B$ e TP compartilham '
              r'grade, agregação, imputação TS-I e reconstrução multilinear. As médias e os desvios padrão '
              r'reproduzidos de TP e Scattered foram conferidos na precisão dos CSVs do lote atual; '
              r'não há comparação com pares individuais preservados desse lote. '
              r'O negrito destaca o menor RMSE médio entre $B$ e TP, incluindo empates nas quatro casas '
              r'publicadas, sem indicar significância ou menor dispersão. '
              r'$\overline{d}^{\mathrm{abl}}=\overline{r_{\mathrm{TP}}-r_B}$: valores negativos favorecem '
              r'o truncamento. Diferenças e testes usam os valores pareados não arredondados, nas unidades '
              r'da resposta de cada conjunto. Testes bilaterais de reamostragem corrigida, com 49 graus '
              r'de liberdade e Holm em 30 contrastes. A análise é exploratória. ' + inference,
              r'\end{minipage}', r'\endgroup', r'\end{table}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = load_summary()
    text = render(rows)
    existing = TARGET.read_text(encoding='utf-8')
    if args.check:
        assert existing == text, 'Table differs from validated current summary.'
        print('Verified 30 rows, 60 mean/SD pairs, 30 differences, Holm p-values and bold minima/ties.')
    else:
        print('*** Begin Patch')
        print('*** Update File: article/manuscrito/tables/reviewer1_ablation.tex')
        for line in list(difflib.unified_diff(existing.splitlines(), text.splitlines(), n=2, lineterm=''))[2:]:
            print('@@' if line.startswith('@@') else line)
        print('*** End Patch')


if __name__ == '__main__':
    main()
